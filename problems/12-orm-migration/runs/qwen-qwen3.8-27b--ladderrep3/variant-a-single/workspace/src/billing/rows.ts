// Row shapes as the data layer hands them to the service layer.
// They mirror the Drizzle schema in ./schema.ts (see MIGRATION_NOTES.md).
export interface AccountRow {
  id: string;
  name: string;
  currency: string;
  invoiceCount: number;
  createdAt: Date;
}

export interface InvoiceRow {
  id: string;
  accountId: string;
  number: string;
  status: string;
  totalMinor: bigint;
  issuedAt: Date | null;
  createdAt: Date;
}

export interface LineItemRow {
  id: string;
  invoiceId: string;
  position: number;
  description: string;
  quantity: number;
  unitPriceMinor: bigint;
}
